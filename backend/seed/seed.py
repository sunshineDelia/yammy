def seed() -> None:
    Base.metadata.create_all(engine)
    db = SessionLocal()
    try:
        food_count = db.scalar(select(func.count()).select_from(Food)) or 0
        attraction_count = db.scalar(select(func.count()).select_from(Attraction)) or 0
        if food_count > 0 or attraction_count > 0:
            print("检测到已有数据，跳过种子。")
            return

        foods = []
        for i, (name, desc, price, cat, rating, rc, tags, addr, img, stores) in enumerate(FOODS):
            image_url = img or GEN_FOOD[i % len(GEN_FOOD)]
            foods.append(Food(
                name=name, description=desc, avg_price=price, rating=rating,
                rating_count=rc, category=cat, tags=tags, address=addr,
                image_url=image_url,
                stores=[Store(name=s_name, address=s_addr) for s_name, s_addr in stores],
            ))

        attractions = []
        for i, (name, desc, open_time, price, rating, rc, level, duration, addr, tags, img) in enumerate(ATTRACTIONS):
            image_url = img or GEN_ATTR[i % len(GEN_ATTR)]
            attractions.append(Attraction(
                name=name, description=desc, open_time=open_time, ticket_price=price,
                rating=rating, rating_count=rc, level=level, duration=duration,
                address=addr, tags=tags, image_url=image_url,
            ))

        db.add_all(foods + attractions)
        db.commit()
        print(f"种子数据完成：{len(foods)} 条美食，{len(attractions)} 条景点。")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
